export const IRAN_PROVINCES = IRAN_PROVINCES_DATA.map((p) => p.name)

export function getCitiesByProvince(provinceName?: string): string[] {
  if (!provinceName) return []
  const found = IRAN_PROVINCES_DATA.find(
    (p) => p.name === provinceName.trim() || p.id === provinceName.trim().toLowerCase(),
  )
  return found ? found.cities : []
}
